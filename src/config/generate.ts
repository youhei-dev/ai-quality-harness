/**
 * Turns an adapter resolution into a commented aiqh.config.jsonc proposal (M1 `aiqh init`).
 */
import { CATEGORY_KINDS, type CategoryKind } from "../types.ts";
import type { Resolution, Suggestion } from "../adapters/types.ts";
import { maskSecrets } from "../security/mask.ts";

export interface GenerateOptions {
  projectName: string;
  resolution: Resolution;
  /** Relative path written as "$schema"; omitted when undefined (not resolvable from the target). */
  schemaPath?: string;
}

const LABEL: Record<CategoryKind, string> = {
  lint: "lint",
  typecheck: "typecheck",
  unit: "unit",
  build: "build",
  security: "security",
  dependency: "dependency",
  e2e: "e2e",
};

function jsonString(s: string): string {
  return JSON.stringify(s);
}

/** The checks that would be written (kind order = category order). */
export function proposedChecks(resolution: Resolution): Suggestion[] {
  const out: Suggestion[] = [];
  for (const kind of CATEGORY_KINDS) {
    const chosen = resolution.byKind[kind].chosen;
    if (chosen?.suggestion) out.push(chosen.suggestion);
  }
  return out;
}

export function generateConfigJsonc(opts: GenerateOptions): string {
  const { resolution } = opts;
  const lines: string[] = [];
  lines.push("// aiqh.config.jsonc — generated by `aiqh init`. Spec: docs/CONFIG_SPEC.md of ai-quality-harness.");
  lines.push("// Edit freely: this file is data only (no secrets belong here). Checks listed below were detected");
  lines.push("// from the repository; commented categories were not detected and are reported NOT_APPLICABLE.");
  lines.push("{");
  if (opts.schemaPath) lines.push(`  "$schema": ${jsonString(opts.schemaPath)},`);
  lines.push('  "version": 1,');
  lines.push(`  "project": { "name": ${jsonString(opts.projectName)}, "type": ${jsonString(resolution.projectType)} },`);
  lines.push('  "defaults": { "timeoutSec": 600, "required": true },');
  lines.push('  "checks": [');
  const checks = proposedChecks(resolution);
  checks.forEach((s, i) => {
    const kindRes = resolution.byKind[s.kind as CategoryKind];
    const chosen = kindRes?.chosen;
    // Adapter text is masked before it lands in a file (M1-R1-003, defence in depth).
    if (chosen) lines.push(`    // ${LABEL[s.kind as CategoryKind]}: ${chosen.adapter} — ${maskSecrets(chosen.reason)}`);
    for (const note of chosen?.notes ?? []) lines.push(`    //   note: ${maskSecrets(note)}`);
    const fields = [`"name": ${jsonString(s.name)}`, `"kind": ${jsonString(s.kind)}`, `"command": ${jsonString(s.command)}`, `"timeoutSec": ${s.timeoutSec}`];
    if (s.required === false) fields.push('"required": false');
    fields.push(`"description": ${jsonString(s.description)}`);
    lines.push(`    { ${fields.join(", ")} }${i < checks.length - 1 ? "," : ""}`);
  });
  for (const kind of CATEGORY_KINDS) {
    const r = resolution.byKind[kind];
    if (r.chosen) continue;
    lines.push(`    // ${LABEL[kind]}: NOT APPLICABLE — ${maskSecrets(r.unavailable.map((u) => u.reason).join(" / ") || "no adapter applies to this repository")}`);
    const hint = r.unavailable.find((u) => u.enableHint)?.enableHint;
    if (hint) lines.push(`    //   to enable: ${maskSecrets(hint)}`);
    for (const note of r.unavailable.flatMap((u) => u.notes ?? []).slice(0, 2)) lines.push(`    //   note: ${maskSecrets(note)}`);
  }
  lines.push("  ]");
  lines.push("}");
  return `${lines.join("\n")}\n`;
}

export const GITIGNORE_LINE = "artifacts/";
export const PROPOSED_SCRIPTS: Readonly<Record<string, string>> = { verify: "aiqh verify" };
