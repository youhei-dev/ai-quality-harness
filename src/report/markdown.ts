import { statusText, summaryText } from "../parse/describe.ts";
import { escapeRawChars } from "../security/raw-chars.ts";
import { CATEGORY_KINDS, type CheckResult, type VerificationReport } from "../types.ts";

const CATEGORY_LABELS: Record<(typeof CATEGORY_KINDS)[number], string> = {
  lint: "Lint",
  typecheck: "Type Check",
  unit: "Unit Test",
  build: "Build",
  security: "Security Scan",
  dependency: "Dependency Scan",
  e2e: "E2E / Browser Test",
};

export function renderMarkdown(report: VerificationReport): string {
  const lines: string[] = [];
  lines.push(`# Verification Report — ${oneLine(report.project.name)}`);
  lines.push("");
  lines.push(
    `## Verdict: **VERIFY ${report.verdict}**${report.interruptedBy ? ` (interrupted by ${report.interruptedBy})` : ""}`,
  );
  lines.push("");
  lines.push("| Item | Value |");
  lines.push("|---|---|");
  // ADR-0038: the run's id, the same value as in latest.json and the history file (older reports have none)
  if (report.runId !== undefined) lines.push(`| Run ID | ${cell(report.runId)} |`);
  lines.push(`| Started | ${report.startedAt} |`);
  lines.push(`| Finished | ${report.finishedAt} |`);
  lines.push(`| Duration | ${formatDuration(report.durationMs)} |`);
  // `git: null` is also what a git that failed leaves (the report carries no reason; the console line does): do not say more than is known
  lines.push(`| Git commit | ${cell(report.git?.commit ?? "(not a git repository, git unavailable, or no commit)")} |`);
  lines.push(`| Git branch | ${cell(report.git?.branch ?? "-")} |`);
  lines.push(`| Working tree | ${report.git ? describeDirty(report.git.dirty) : "-"} |`);
  lines.push(`| Exit code | ${report.exitCode} |`);
  if (report.interruptedBy) lines.push(`| Interrupted by | ${report.interruptedBy} (run did not complete; later checks SKIPPED) |`);
  lines.push(`| Config | ${cell(report.configPath)} |`);
  lines.push(`| Tool | ${report.tool.name} ${report.tool.version} |`);
  lines.push("");

  lines.push("## Summary");
  lines.push("");
  const s = report.summary;
  lines.push(
    `Total ${s.total} · PASS ${s.passed} · FAIL ${s.failed} · SKIPPED ${s.skipped} · required failed ${s.requiredFailed}`,
  );
  lines.push("");

  lines.push("## Categories");
  lines.push("");
  lines.push("| Category | Status |");
  lines.push("|---|---|");
  for (const kind of CATEGORY_KINDS) {
    lines.push(`| ${CATEGORY_LABELS[kind]} | ${report.categories[kind]} |`);
  }
  lines.push("");

  lines.push("## Checks");
  lines.push("");
  lines.push("| # | Name | Kind | Required | Status | Duration | Exit | Command |");
  lines.push("|---|---|---|---|---|---|---|---|");
  report.checks.forEach((c, i) => {
    lines.push(
      `| ${i + 1} | ${cell(c.name)} | ${c.kind} | ${c.required ? "yes" : "no"} | ${c.status} | ${formatDuration(c.durationMs)} | ${c.exitCode ?? "-"} | \`${cell(c.command)}\` |`,
    );
  });
  lines.push("");

  lines.push(...renderParsed(report.checks));

  const failures = report.checks.filter((c) => c.status !== "PASS");
  if (failures.length > 0) {
    lines.push("## Failure Details");
    lines.push("");
    for (const c of failures) {
      lines.push(...renderFailure(c));
    }
  }

  lines.push("---");
  lines.push(
    "Generated by ai-quality-harness. Secret-looking strings are replaced with `[REDACTED:<category>]`.",
  );
  lines.push("");
  return lines.join("\n");
}

/**
 * ADR-0028: what was read from each check's output, only when some check was read (a report without one renders as before). The names
 * are values of the masked report, written on one line each like the other values, as the lines of one code block per check
 * (M2-2-PS-R1-001): they come from a tool's output, and inside a code block Markdown reads no link, image, HTML, character reference
 * or emphasis. No line of the list can close the block (each starts with "- "); the fence is still longer than any run inside.
 */
function renderParsed(checks: readonly CheckResult[]): string[] {
  if (!checks.some((c) => c.parsed !== undefined && c.parsed.status !== "not-applicable")) return [];
  const lines: string[] = [];
  lines.push("## Parsed Output");
  lines.push("");
  lines.push("Read from each check's output for display only: the verdict and the exit code do not use it (ADR-0028).");
  lines.push("");
  lines.push("| # | Check | Tool | Status | Summary |");
  lines.push("|---|---|---|---|---|");
  checks.forEach((c, i) => {
    const p = c.parsed;
    if (p === undefined) return;
    lines.push(`| ${i + 1} | ${cell(c.name)} | ${p.tool ?? "-"} | ${statusText(p)} | ${p.status === "parsed" ? cell(summaryText(p)) : "-"} |`);
  });
  lines.push("");
  for (const c of checks) {
    const p = c.parsed;
    if (p === undefined || p.status !== "parsed" || (p.items.length === 0 && p.itemsOmitted === 0)) continue;
    lines.push(`### ${oneLine(c.name)} — ${p.tool ?? "-"}`);
    lines.push("");
    const list = p.items.map((item) => `- ${oneLine(item.kind)}: ${oneLine(item.name)}`);
    if (p.itemsOmitted > 0) list.push(`- … ${p.itemsOmitted} more (not listed)`);
    const fence = fenceFor(list.join("\n"));
    lines.push(`${fence}text`, ...list, fence);
    lines.push("");
  }
  return lines;
}

function renderFailure(c: CheckResult): string[] {
  const lines: string[] = [];
  lines.push(`### ${oneLine(c.name)} — ${c.status}`);
  lines.push("");
  lines.push(`- Command: \`${cell(c.command)}\` (cwd: \`${oneLine(c.cwd)}\`)`);
  // M2-2-PS-R1-001 (S2): the summary is a line of the tool's output (or aiqh's reason): one code span, read as text
  const summary = c.errorSummary ?? null;
  lines.push(`- Summary: ${summary === null ? "-" : codeSpan(oneLine(summary))}`);
  if (c.timedOut) lines.push(`- Timed out after ${c.timeoutSec}s`);
  if (c.signal) lines.push(`- Signal: ${c.signal}`);
  if (c.outputTruncated) lines.push("- Output was truncated (tail only)");
  lines.push("");
  if (c.stderrTail.trim().length > 0) {
    const fence = fenceFor(c.stderrTail);
    lines.push("<details><summary>stderr (tail)</summary>");
    lines.push("");
    lines.push(`${fence}text`);
    lines.push(c.stderrTail.trimEnd());
    lines.push(fence);
    lines.push("");
    lines.push("</details>");
    lines.push("");
  }
  if (c.stdoutTail.trim().length > 0) {
    const fence = fenceFor(c.stdoutTail);
    lines.push("<details><summary>stdout (tail)</summary>");
    lines.push("");
    lines.push(`${fence}text`);
    lines.push(c.stdoutTail.trimEnd());
    lines.push(fence);
    lines.push("");
    lines.push("</details>");
    lines.push("");
  }
  return lines;
}

/** A fence longer than any run of backticks in the text, so output that contains ``` cannot end the block early. */
function fenceFor(text: string): string {
  const longest = Math.max(0, ...[...text.matchAll(/`+/g)].map((m) => m[0].length));
  return "`".repeat(Math.max(3, longest + 1));
}

/**
 * One-line text as one code span that shows it as it is (CommonMark 0.31.2 §6.1, ADR-0028 addendum v0.8.1). The backtick string is
 * one longer than the longest run in the text, so no run inside can close it (the first backtick string of the same length would). A
 * space goes at each end when the text starts or ends with a backtick (it would join the backtick string) or starts and ends with a
 * space without being only spaces (Markdown takes one space off each end of such content): Markdown then takes exactly those two off.
 * Empty text stays empty (an empty code span cannot be written).
 */
function codeSpan(text: string): string {
  if (text.length === 0) return "";
  const longest = Math.max(0, ...[...text.matchAll(/`+/g)].map((m) => m[0].length));
  const ticks = "`".repeat(longest + 1);
  const pad = text.startsWith("`") || text.endsWith("`") || (text.startsWith(" ") && text.endsWith(" ") && !/^ +$/.test(text)) ? " " : "";
  return `${ticks}${pad}${text}${pad}${ticks}`;
}

function describeDirty(dirty: boolean | null): string {
  if (dirty === null) return "unknown";
  return dirty ? "dirty" : "clean";
}

export function formatDuration(ms: number): string {
  if (ms < 1000) return `${ms}ms`;
  const sec = ms / 1000;
  // Round the whole value to the unit it is shown in before splitting it (ROADMAP item 38): 59.96 s is "1m00s", not "60.0s", and 239.6 s
  // is "4m00s", not "3m60s". Below a minute the shown value is toFixed(1), as before; from a minute, whole seconds.
  const tenths = sec.toFixed(1);
  if (Number(tenths) < 60) return `${tenths}s`;
  const whole = Math.round(sec);
  return `${Math.floor(whole / 60)}m${(whole % 60).toString().padStart(2, "0")}s`;
}

/** A value in a table cell or between backticks: one line, and a `|` stays in its cell. */
function cell(text: string): string {
  return escapeCell(oneLine(text));
}

/** A value that must stay on one line (a heading, a table cell, a list item): LF and TAB become notation like the forbidden characters. */
function oneLine(text: string): string {
  return escapeRawChars(text);
}

function escapeCell(text: string): string {
  return text.replace(/\|/g, "\\|").replace(/\r?\n/g, " ");
}
